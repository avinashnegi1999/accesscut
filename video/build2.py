"""Time the film to its voice, then write film2.html and captions.vtt.

    python video/build2.py

Line durations come from video/voice/line_NN.mp3 when they exist (generated by voice.py);
otherwise they are estimated, so the film can be previewed before any audio exists.
Each line starts `gap` seconds after the previous line ends.
"""
import json
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).parent
FFPROBE = r"C:/Users/avina/AppData/Local/Microsoft/WinGet/Packages/Gyan.FFmpeg.Essentials_Microsoft.Winget.Source_8wekyb3d8bbwe/ffmpeg-9.0.1-essentials_build/bin/ffprobe.exe"
LIVE_SECONDS = 11.5   # length of live.mp4
TAIL = 3.0            # silence after the last line


def duration(path):
    out = subprocess.run([FFPROBE, "-v", "error", "-show_entries", "format=duration",
                          "-of", "default=nk=1:nw=1", str(path)], capture_output=True, text=True).stdout
    return float(out.strip())


def timing():
    script = json.loads((HERE / "script.json").read_text(encoding="utf-8"))
    lines, t, measured = [], 0.0, 0
    for i, ln in enumerate(script["lines"]):
        mp3 = HERE / "voice" / f"line_{i:02d}.mp3"
        if mp3.exists():
            dur, measured = duration(mp3), measured + 1
        else:
            dur = len(ln["text"].split()) / 2.5 + 0.35
        start = t + ln["gap"]
        # The live clip needs room: the line after the live scene waits for the clip to finish.
        if lines and lines[-1]["scene"] == "live" and ln["scene"] != "live":
            live_start = next(l["start"] for l in lines if l["scene"] == "live") - 0.6
            start = max(start, live_start + 0.8 + LIVE_SECONDS + 1.2)
        lines.append({"i": i, "scene": ln["scene"], "text": ln["text"], "start": round(start, 3), "dur": round(dur, 3)})
        t = start + dur
    scenes, order = [], []
    for ln in lines:
        if ln["scene"] not in order:
            order.append(ln["scene"])
    for k, sid in enumerate(order):
        first = next(l for l in lines if l["scene"] == sid)
        start = 0.0 if k == 0 else max(0.0, first["start"] - 0.7)
        scenes.append({"id": sid, "start": round(start, 3)})
    total = round(t + TAIL, 3)
    for k, sc in enumerate(scenes):
        sc["end"] = scenes[k + 1]["start"] + 0.35 if k + 1 < len(scenes) else total
    return {"lines": lines, "scenes": scenes, "total": total, "measured": measured}


def vtt(lines):
    def ts(x):
        h, m, s = int(x // 3600), int(x % 3600 // 60), x % 60
        return f"{h:02d}:{m:02d}:{s:06.3f}"
    out = ["WEBVTT", ""]
    for ln in lines:
        out += [f"{ts(ln['start'])} --> {ts(ln['start'] + ln['dur'])}", ln["text"], ""]
    return "\n".join(out)


def main():
    tm = timing()
    html = (HERE / "film2.template.html").read_text(encoding="utf-8")
    inline = {
        "TIMING": tm,
        "RUN": json.loads((HERE / "trace_big_payroll.json").read_text(encoding="utf-8")),
        "REFUSE": json.loads((HERE / "trace_big_wiki.json").read_text(encoding="utf-8")),
        "FIXTURE": json.loads((HERE.parent / "fixture_big.json").read_text(encoding="utf-8")),
    }
    for key, val in inline.items():
        marker = f"/*{key}*/null"
        assert marker in html, marker
        html = html.replace(marker, json.dumps(val))
    (HERE / "film2.html").write_text(html, encoding="utf-8")
    (HERE / "captions.vtt").write_text(vtt(tm["lines"]), encoding="utf-8")
    print(f"film2.html: {tm['total']:.1f}s, {len(tm['lines'])} lines ({tm['measured']} measured from audio)")
    for sc in tm["scenes"]:
        print(f"  {sc['id']:8} {sc['start']:6.1f} - {sc['end']:6.1f}")


if __name__ == "__main__":
    main()
